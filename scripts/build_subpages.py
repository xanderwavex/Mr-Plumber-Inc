def credits(page, images):
    people = []
    for name, user in [page["hero_credit"]] + [(images[c["img"]]["name"], images[c["img"]]["user"]) for c in page["cards"]]:
        if (name, user) not in people:
            people.append((name, user))
    links = ", ".join(f'<a href="https://unsplash.com/@{u}?{UTM}" target="_blank" rel="noopener">{e(n)}</a>' for n, u in people)
    return f'    <p class="scard-credits">Photos: {links} on <a href="https://unsplash.com/?{UTM}" target="_blank" rel="noopener">Unsplash</a></p>'


