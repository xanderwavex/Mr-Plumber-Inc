def build_page(page, images):
    return "".join([
        head(page), "\n", nav(page["section"]), '\n<main id="main">\n',
        hero(page), intro(page), grid(page, images), industries(page), why(page), cta(page),
        "\n</main>\n", FOOTER,
    ])


def validate(data):
    seen = {}
    for page in data["pages"]:
        for c in page["cards"]:
            pid = c["img"]
            if pid not in data["images"]:
                sys.exit(f"Missing image entry for {pid} ({page['slug']} / {c['title']})")
            if pid in seen:
                sys.exit(f"Image {pid} is used twice: {seen[pid]} and {page['slug']} / {c['title']}")
            seen[pid] = f"{page['slug']} / {c['title']}"
            if not (3 <= len(c["included"]) <= 5 and 2 <= len(c["signs"]) <= 4):
                sys.exit(f"List length out of range on {page['slug']} / {c['title']}")
    text = json.dumps(data, ensure_ascii=False)
    for bad in ("—", "–", "lorem", "$79"):
        if bad in text:
            sys.exit(f"Disallowed text {bad!r} found in data/subpages.json")


def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    validate(data)
    for page in data["pages"]:
        out = ROOT / f"{page['slug']}.html"
        out.write_text(build_page(page, data["images"]), encoding="utf-8")
        print(f"wrote {out.name}")


if __name__ == "__main__":
    main()
