def e(text):
    return escape(text, quote=True)


def img_url(pid, w, h=None, q=80):
    size = f"&amp;h={h}" if h else ""
    return f"https://images.unsplash.com/{pid}?w={w}{size}&amp;q={q}&amp;auto=format&amp;fit=crop"


def quote_href(page, need=None):
    href = f"index.html?service={page['service']}"
    if need:
        href += "&amp;need=" + quote_plus(need)
    return href + "#contact"


